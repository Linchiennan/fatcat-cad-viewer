"""Build the Android APK of fatcat-cad: runtime → dxf-viewer patches → build identity → tsc → vite → Capacitor sync →
Gradle (APK + JVM unit tests). Logs go to build-logs/.

Usage: python scripts/build-apk.py [versionCode] [--release]
  versionCode   default 30 (待決 30: must be higher than the version installed on the phones); > 3 and <= 2,100,000,000.
  --release     assembleRelease. Signed only when all four of FATCAT_KEYSTORE_FILE, FATCAT_KEYSTORE_PASSWORD,
                FATCAT_KEY_ALIAS, FATCAT_KEY_PASSWORD are set in the environment (same key as the installed app,
                otherwise Android refuses the update); partial settings fail the build. Without them the APK is unsigned.
"""
from pathlib import Path
import hashlib, json, os, re, subprocess, sys

w = Path(__file__).resolve().parent.parent
args = [a for a in sys.argv[1:] if not a.startswith("--")]
release = "--release" in sys.argv[1:]
package_only = "--package-only" in sys.argv[1:]  # User performs final functional testing.
code = args[0] if args else "30"
if not re.fullmatch(r"[0-9]{1,10}", code) or not 3 < int(code) <= 2_100_000_000:
    raise SystemExit("versionCode must be an integer greater than 3 and at most 2100000000")

e = os.environ.copy()
env_file = Path("E:/cad-analysis/devtools/process-env.json")  # this machine's Android SDK paths
if env_file.exists():
    e.update(json.loads(env_file.read_text()))
e["JAVA_HOME"] = "E:/cad-analysis/rea/backends/jdk/jdk-21.0.12.1+1"
e["PATH"] = e["JAVA_HOME"] + "/bin;" + e["PATH"]
tmp = w.parent / "_tmp"
tmp.mkdir(exist_ok=True)
e["TMPDIR"] = e["TEMP"] = e["TMP"] = str(tmp)
e["FATCAT_VERSION_CODE"] = code
logs = w / "build-logs"
logs.mkdir(exist_ok=True)

# Build identity shown on the home screen ("code30"); restored afterwards.
identity = w / "src/app/buildIdentity.ts"
inputs = sorted(p for base in ["src", "public", "web", "scripts", "android/app/src"] for p in (w / base).rglob("*")
                if p.is_file() and p != identity and "assets" not in p.relative_to(w).parts)
inputs += [w / n for n in ["package.json", "package-lock.json", "vite.config.ts", "index.html", "capacitor.config.ts"] if (w / n).is_file()]
digests = {p.relative_to(w).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest() for p in inputs}
build = hashlib.sha256(json.dumps({"inputs": digests, "variant": "apk", "code": code}, sort_keys=True).encode()).hexdigest()[:12]

node = lambda *a: ["node", *a]
task = "assembleRelease" if release else "assembleDebug"
steps = [
    ("runtime", node("scripts/copy-runtime.mjs"), w),
    # dxf-viewer patches (ours); each script is idempotent and refuses an unexpected dxf-viewer version.
    ("patch-cjk-fonts", node("scripts/patch-cjk-fonts.mjs"), w),
    ("patch-engineering", node("scripts/patch-engineering.mjs"), w),
    ("patch-mtext-height", node("scripts/patch-mtext-height.mjs"), w),
    ("patch-mtext-cjkwrap", node("scripts/patch-mtext-cjkwrap.mjs"), w),
    # App and build-config sources only; test files are type-checked by `tsc -b` / vitest, not by the build.
    ("tsc", node("node_modules/typescript/bin/tsc", "-b", "tsconfig.app.json", "tsconfig.node.json"), w),
    ("vite", node("node_modules/vite/bin/vite.js", "build"), w),
    ("sync", node("node_modules/@capacitor/cli/bin/capacitor", "sync", "android"), w),
    ("gradle", ["cmd", "/c", str(w / "android" / "gradlew.bat"), task, *([] if package_only else ["compileDebugUnitTestJavaWithJavac"]), "--no-daemon"], w / "android"),
]
original_identity = identity.read_bytes() if identity.exists() else None
identity.write_text(f'// Generated by scripts/build-apk.py (APK)\nexport const BUILD_CODE = {int(code)};\nexport const BUILD_ID = "{build}";\n', encoding="utf8")
try:
    for name, cmd, cwd in steps:
        with (logs / f"{name}.log").open("wb") as f:
            p = subprocess.run(cmd, cwd=cwd, env=e, stdout=f, stderr=subprocess.STDOUT)
        print("apk", name, p.returncode, flush=True)
        if p.returncode:
            raise SystemExit(p.returncode)
finally:
    if original_identity is not None:
        identity.write_bytes(original_identity)

# Packaging-only handoff: no JVM or final functional tests, as requested.
if package_only:
    out = w / "android/app/build/outputs/apk" / ("release" if release else "debug")
    apks = sorted(out.glob("*.apk"))
    if not apks:
        raise SystemExit("APK missing")
    receipt = {"versionCode": int(code), "build": build, "sourceDigests": digests,
               "functionalTestsRun": False, "variant": "release" if release else "debug",
               "artifacts": [{"path": str(p), "bytes": p.stat().st_size,
                              "sha256": hashlib.sha256(p.read_bytes()).hexdigest()} for p in apks]}
    (logs / "apk-build.json").write_text(json.dumps(receipt, ensure_ascii=False, indent=2), encoding="utf8")
    print("APK", json.dumps({k: v for k, v in receipt.items() if k != "sourceDigests"}, ensure_ascii=False))
    raise SystemExit(0)

# JVM unit tests (T21 9.2). Run with plain java: Gradle's test worker cannot load classes under this Chinese path.
gradle_home = Path(e.get("GRADLE_USER_HOME", Path.home() / ".gradle")) / "caches/modules-2/files-2.1"
jars = [next(gradle_home.glob(f"{group}/{name}/{ver}/*/{name}-{ver}.jar"), None) for group, name, ver in [("junit", "junit", "4.13.2"), ("org.hamcrest", "hamcrest-core", "1.3")]]
if None in jars:
    raise SystemExit("JUnit jars not found in the Gradle cache")
javac_out = w / "android/app/build/intermediates/javac"
classpath = [javac_out / "debugUnitTest/compileDebugUnitTestJavaWithJavac/classes", javac_out / "debug/compileDebugJavaWithJavac/classes", *jars]
tests = sorted(p.relative_to(classpath[0]).with_suffix("").as_posix().replace("/", ".") for p in classpath[0].rglob("*Test.class"))
with (logs / "junit.log").open("wb") as f:
    p = subprocess.run([e["JAVA_HOME"] + "/bin/java", "-cp", os.pathsep.join(map(str, classpath)), "org.junit.runner.JUnitCore", *tests], env=e, stdout=f, stderr=subprocess.STDOUT)
print("apk junit", p.returncode, tests, flush=True)
if p.returncode or not tests:
    raise SystemExit(p.returncode or 1)

out = w / "android/app/build/outputs/apk" / ("release" if release else "debug")
apks = sorted(out.glob("*.apk"))
for apk in apks:
    print("APK", apk.as_posix(), apk.stat().st_size, "versionCode", code, "build", build)
if not apks:
    raise SystemExit("APK missing")
