"""Build the web version (PWA for iPhone and Android browsers) into dist-web/; never touches dist/ used by the APK.
Steps: copy runtime → patch dxf-viewer → write build identity → tsc → vite (VITE_FATCAT_WEB=1) → manifest, icons,
iOS tags and the offline service worker → self-check. Logs go to build-logs/web-*.log.
Usage: python scripts/web-build.py
"""
from pathlib import Path
import hashlib, json, os, shutil, subprocess

w = Path(__file__).resolve().parent.parent
out = w / 'dist-web'
identity = w / 'src/app/buildIdentity.ts'
logs = w / 'build-logs'

# Build id = hash of every input, so the same sources always give the same id. vendor/ holds the DWG engine: a new
# engine alone must give a new id, or the offline cache keeps serving the old one (2026-10-28: 02e89fb kept 8a4d5efb7c08).
inputs = sorted(p for base in ['src', 'public', 'web', 'scripts', 'licenses', 'vendor'] for p in (w / base).rglob('*')
                if p.is_file() and p != identity and p.name != 'build-apk.py' and '__pycache__' not in p.parts
                and not p.relative_to(w).as_posix().startswith(('public/runtime/', 'public/licenses/')))
inputs += [w / n for n in ['package.json', 'package-lock.json', 'vite.config.ts', 'index.html', 'usage.html', 'WEB_PRIVACY.md', 'firestore.rules', 'LICENSE', 'NOTICE.md', 'THIRD_PARTY_LICENSES.md', 'PRIVACY_POLICY.md'] if (w / n).is_file()]
digests = {p.relative_to(w).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest() for p in inputs}
build = hashlib.sha256(json.dumps({'inputs': digests, 'variant': 'web'}, sort_keys=True).encode()).hexdigest()[:12]

env = os.environ.copy()
env['VITE_FATCAT_WEB'] = '1'
tmp = w / 'build-logs/tmp'
tmp.mkdir(parents=True, exist_ok=True)
env['TMPDIR'] = env['TEMP'] = env['TMP'] = str(tmp)
logs.mkdir(exist_ok=True)

node = lambda *a: ['node', *a]
steps = [
    ('runtime', node('scripts/copy-runtime.mjs')),
    ('patch-cjk-fonts', node('scripts/patch-cjk-fonts.mjs')),
    ('patch-engineering', node('scripts/patch-engineering.mjs')),
    ('patch-mtext-height', node('scripts/patch-mtext-height.mjs')),
    # App and build-config sources only; test files are type-checked by `tsc -b` / vitest, not by the build.
    ('tsc', node('node_modules/typescript/bin/tsc', '-b', 'tsconfig.app.json', 'tsconfig.node.json')),
    ('vite', node('node_modules/vite/bin/vite.js', 'build', '--outDir', 'dist-web', '--emptyOutDir')),
]

# The web build is code 0. The identity file is restored afterwards so the
# source tree and the APK build keep their own values.
original_identity = identity.read_bytes() if identity.exists() else None
identity.write_text(f'// Generated by scripts/web-build.py (web)\nexport const BUILD_CODE = 0;\nexport const BUILD_ID = "{build}";\n', encoding='utf8')
try:
    for name, cmd in steps:
        with (logs / f'web-{name}.log').open('wb') as f:
            p = subprocess.run(cmd, cwd=w, env=env, stdout=f, stderr=subprocess.STDOUT)
        print('web', name, p.returncode, flush=True)
        if p.returncode:
            raise SystemExit(p.returncode)
finally:
    if original_identity is not None:
        identity.write_bytes(original_identity)

# Manifest, icons and home-screen tags.
shutil.copytree(w / 'web/icons', out / 'icons', dirs_exist_ok=True)
shutil.copy2(w / 'web/manifest.webmanifest', out / 'manifest.webmanifest')
shutil.copy2(w / 'WEB_PRIVACY.md', out / 'WEB_PRIVACY.md')
# 訪客試用的示範圖（自己畫的虛構平面，用戶 2026-10-29），只放這三個檔，其他圖檔一律不得出現在網站。
DEMO = ['示範-住宅平面.dwg', '示範-圖框.dwg', '示範-住宅平面.pdf']
(out / 'demo').mkdir(exist_ok=True)
for name in DEMO:
    shutil.copy2(w / 'web/demo' / name, out / 'demo' / name)
# Do not publish the native zero-collection notice as the web policy.
shutil.copy2(w / 'WEB_PRIVACY.md', out / 'licenses/PRIVACY_POLICY.md')
(out / '.nojekyll').write_text('', encoding='utf8')
tags = ('<link rel="manifest" href="manifest.webmanifest" />'
        '<link rel="icon" type="image/png" href="icons/favicon-32.png" />'
        '<link rel="apple-touch-icon" href="icons/apple-touch-icon.png" />'
        '<meta name="mobile-web-app-capable" content="yes" />'
        '<meta name="apple-mobile-web-app-capable" content="yes" />'
        '<meta name="apple-mobile-web-app-title" content="大肥貓CAD" />'
        '<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent" />')
index = (out / 'index.html').read_text(encoding='utf8')
assert '</head>' in index and 'rel="manifest"' not in index and 'serviceWorker' not in index
(out / 'index.html').write_text(index.replace('</head>', tags + '</head>', 1), encoding='utf8')

# Offline cache: the app shell, plus the runtime (DWG engine, archive reader, PDF worker and data) and the
# fonts, all stored at install so the first drawing also opens offline.
rel = lambda p: './' + p.relative_to(out).as_posix()
files_under = lambda d: [rel(p) for p in sorted((out / d).rglob('*')) if p.is_file()] if (out / d).is_dir() else []
core = ['./', './index.html', './usage.html', './WEB_PRIVACY.md', './manifest.webmanifest'] + [rel(p) for p in sorted(out.glob('*.png'))]
core += files_under('assets') + files_under('icons')
runtime = files_under('runtime') + files_under('fonts') + files_under('demo')
sw = (w / 'web/sw.template.js').read_text(encoding='utf8')
sw = sw.replace('__BUILD_ID__', build).replace('__PRECACHE__', json.dumps(core, ensure_ascii=False)).replace('__RUNTIME_PRECACHE__', json.dumps(runtime, ensure_ascii=False))
(out / 'sw.js').write_text(sw, encoding='utf8')

# Self-check: no drawings or credentials shipped, every cached entry exists, runtime and fonts are in the cache.
files = [p for p in out.rglob('*') if p.is_file()]
demo = {out / 'demo' / n for n in DEMO}
banned = [p for p in files if p not in demo and p.suffix.lower() in ['.dwg', '.dxf', '.jks', '.keystore', '.pem', '.p12'] or any(k in p.name.lower() for k in ['client_secret', 'google_token', 'local.properties'])]
assert not banned, banned
for url in core + runtime:
    assert url == './' or (out / url[2:]).is_file(), url
for needed in ['./runtime/libredwg/libredwg-web.wasm', './runtime/libarchive/libarchive.wasm', './runtime/pdfjs/pdf.worker.min.mjs', './fonts/NotoSansCJKtc-Regular.otf', './fonts/NotoSansCJKtc-Light.otf', './fonts/LiberationSans-Regular.ttf']:
    assert needed in runtime, needed
mf = json.loads((out / 'manifest.webmanifest').read_text(encoding='utf8'))
for icon in mf['icons']:
    assert (out / icon['src']).is_file(), icon
text = (out / 'sw.js').read_text(encoding='utf8')
assert '__BUILD_ID__' not in text and '__PRECACHE__' not in text and '__RUNTIME_PRECACHE__' not in text
size = lambda urls: sum((out / u[2:]).stat().st_size for u in urls if u != './')
summary = {'build': build, 'files': len(files), 'totalBytes': sum(p.stat().st_size for p in files),
           'coreEntries': len(core), 'coreBytes': size(core), 'runtimeEntries': len(runtime), 'runtimeBytes': size(runtime)}
(logs / 'web-build.json').write_text(json.dumps(summary, indent=2), encoding='utf8')
print('WEB', json.dumps(summary))
